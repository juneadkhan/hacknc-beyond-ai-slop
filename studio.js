$('reference').addEventListener('change', preview);
$('undo').addEventListener('click', () => {
  if (!history.length) return message('No applied revision to undo yet.');
  applied = history.pop();
  $('css').value = applied;
  $('reference').value = 'work';
  preview();
  save();
  message('Previous applied stylesheet restored.');
});
