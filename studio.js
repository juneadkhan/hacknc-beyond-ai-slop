const $ = (id) => document.getElementById(id);
const key = 'hacknc-design-studio-v1';
const initialDirection = $('direction').value;
let applied = BUNDLE.styles.baseline;
let history = [];
let storageAvailable = true;
function message(text) {
  $('status').textContent = text;
}
function appDocument(css) {
  // Isolated preview has no same-origin access and cannot make network requests.
  const safeCSS = css.replace(/<\/style/gi, '/* closing style tag removed */');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; base-uri 'none'; form-action 'none'"><title>Friday · My workshop design</title><style>${BUNDLE.base}\n${safeCSS}</style></head><body>${BUNDLE.body}<script>${BUNDLE.appJS}<\/script></body></html>`;
}
function save() {
  try {
    localStorage.setItem(
      key,
      JSON.stringify({
        css: $('css').value,
        applied,
        guide: $('guide').value,
        direction: $('direction').value
      })
    );
  } catch {
    storageAvailable = false;
  }
}
function preview() {
  const selected = $('reference').value;
  const css = selected === 'work' ? applied : BUNDLE.styles[selected];
  $('preview').srcdoc = appDocument(css);
  $('preview-heading').textContent =
    selected === 'work'
      ? 'Your preview'
      : `${selected[0].toUpperCase() + selected.slice(1)} reference`;
}
function cleanCSS(input) {
  const cssBlock = input.match(/```css\s*\n([\s\S]*?)```/i);
  return cssBlock
    ? cssBlock[1].trim()
    : input
        .trim()
        .replace(/^```(?:\w+)?\s*\n/, '')
        .replace(/\n```\s*$/, '')
        .trim();
}
function apply() {
  const css = cleanCSS($('css').value);
  if (/<\/?(?:html|head|body|style|script)\b/i.test(css))
    return message('That looks like HTML. Ask your AI for CSS only, without HTML or JavaScript.');
  if (!css || !css.includes('{') || !css.includes('}'))
    return message('Paste a complete CSS stylesheet, then apply it.');
  history.push(applied);
  history = history.slice(-20);
  applied = css;
  $('css').value = css;
  $('reference').value = 'work';
  preview();
  save();
  message(
    `CSS applied. Check mobile, filters, and bill details.${storageAvailable ? ' Saved in this browser.' : ' Browser storage unavailable; download your work.'}`
  );
}
async function copy(text, label) {
  try {
    await navigator.clipboard.writeText(text);
    message(`${label} copied. Paste it into your AI chat.`);
  } catch {
    $('prompt-fallback').hidden = false;
    $('prompt-fallback').open = true;
    $('prompt-text').value = text;
    $('prompt-text').focus();
    $('prompt-text').select();
    message('Clipboard unavailable. The text is selected below; press Ctrl/⌘ + C.');
  }
}
function download(content, filename, type) {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
