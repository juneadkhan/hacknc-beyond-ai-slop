$('copy-build').addEventListener('click', () => copy(buildPrompt(), 'Implementation prompt'));
$('copy-revise').addEventListener('click', () =>
  copy(critiquePrompt(), 'Critique prompt; replace the observation placeholder before sending')
);
$('copy-source').addEventListener('click', () =>
  copy(appDocument(BUNDLE.styles.baseline), 'Original source')
);
$('copy-reference').addEventListener('click', () => {
  const choice = $('reference').value;
  copy(choice === 'work' ? applied : BUNDLE.styles[choice], 'Stylesheet');
});
$('export').addEventListener('click', () => {
  if (cleanCSS($('css').value) !== applied)
    return message('You have unapplied CSS edits. Apply them before downloading your app.');
  download(appDocument(applied), 'my-friday.html', 'text/html');
  message('Your applied app downloaded. Open it in a browser to share your design.');
});
$('export-guide').addEventListener('click', () => {
  download(
    '# Friday design system\n\nDirection: ' + $('direction').value + '\n\n' + $('guide').value,
    'my-design-system.md',
    'text/markdown'
  );
  message('Design guide downloaded.');
});
$('import-css').addEventListener('click', () => $('css-file').click());
$('css-file').addEventListener('change', async (event) => {
  const file = event.target.files[0];
  if (!file) return;
  if (file.size > 250000) {
    message('Choose a CSS file smaller than 250 KB.');
    event.target.value = '';
    return;
  }
  $('css').value = await file.text();
  save();
  message('CSS imported into the editor. Apply it to inspect the result.');
  event.target.value = '';
});
function width(mobile) {
  $('preview').classList.toggle('mobile', mobile);
  $('mobile').setAttribute('aria-pressed', String(mobile));
  $('desktop').setAttribute('aria-pressed', String(!mobile));
}
$('mobile').addEventListener('click', () => width(true));
$('desktop').addEventListener('click', () => width(false));
$('reset').addEventListener('click', () => $('reset-dialog').showModal());
$('cancel-reset').addEventListener('click', () => $('reset-dialog').close());
$('confirm-reset').addEventListener('click', () => {
  history.push(applied);
  applied = BUNDLE.styles.baseline;
  $('css').value = applied;
  $('guide').value = '';
  $('direction').value = initialDirection;
  $('reference').value = 'work';
  $('reset-dialog').close();
  preview();
  save();
  message('Original restored. You can undo the CSS reset.');
});
